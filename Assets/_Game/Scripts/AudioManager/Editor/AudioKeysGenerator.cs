using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using UnityEditor;
using UnityEngine;

/// <summary>
/// Regenerates AudioKeys.cs whenever something changes under Resources/Audio.
/// </summary>
public class AudioKeysGenerator : AssetPostprocessor
{
    private const string AUDIO_ROOT = "Assets/Resources/Audio/";
    private const string OUTPUT_PATH = "Assets/_Game/Scripts/AudioManager/AudioKeys.cs";

    private static void OnPostprocessAllAssets(string[] imported, string[] deleted, string[] moved, string[] movedFrom)
    {
        if (!imported.Concat(deleted).Concat(moved).Concat(movedFrom).Any(p => p.StartsWith(AUDIO_ROOT))) return;
        Generate();
    }

    [MenuItem("Tools/Audio/Regenerate Audio Keys")]
    public static void Generate()
    {
        var sb = new StringBuilder();
        sb.AppendLine("// Auto-generated by AudioKeysGenerator from Resources/Audio. Do not edit.");
        sb.AppendLine();
        AppendClass(sb, "SfxKeys", "Sfx");
        sb.AppendLine();
        AppendClass(sb, "MusicKeys", "Music");

        var content = sb.ToString();
        if (File.Exists(OUTPUT_PATH) && File.ReadAllText(OUTPUT_PATH) == content) return;

        File.WriteAllText(OUTPUT_PATH, content);
        AssetDatabase.ImportAsset(OUTPUT_PATH);
    }

    private static void AppendClass(StringBuilder sb, string className, string folder)
    {
        var folderPath = AUDIO_ROOT + folder;
        sb.AppendLine($"public static class {className}");
        sb.AppendLine("{");

        if (AssetDatabase.IsValidFolder(folderPath))
        {
            var paths = AssetDatabase.FindAssets("t:AudioClip", new[] { folderPath })
                .Select(AssetDatabase.GUIDToAssetPath)
                .OrderBy(p => p);
            var names = new HashSet<string>();

            foreach (var path in paths)
            {
                var key = Path.ChangeExtension(path.Substring(folderPath.Length + 1), null);
                var name = ToConstName(key);
                if (!names.Add(name))
                {
                    Debug.LogError($"[Audio] Duplicate key '{name}' from '{path}', skipped.");
                    continue;
                }
                sb.AppendLine($"    public const string {name} = \"{key}\";");
            }
        }

        sb.AppendLine("}");
    }

    private static string ToConstName(string key)
    {
        var ascii = string.Concat(key.Normalize(NormalizationForm.FormD)
                .Where(c => CharUnicodeInfo.GetUnicodeCategory(c) != UnicodeCategory.NonSpacingMark))
            .Replace('đ', 'd').Replace('Đ', 'D');
        var name = Regex.Replace(ascii, "([a-z0-9])([A-Z])", "$1_$2");
        name = Regex.Replace(name, "[^A-Za-z0-9]+", "_").Trim('_').ToUpperInvariant();
        return char.IsDigit(name[0]) ? "_" + name : name;
    }
}
